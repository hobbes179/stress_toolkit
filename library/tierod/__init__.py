"""
`library.tierod` — analysis kernel for the tie-rod layout module.

**This package must never import Streamlit.** It is pure numpy / dataclasses so
it can be unit-tested standalone and reused outside the app. All UI lives in
`apps/tierod/`.

Units: IPS throughout (lb, in, psi). Rod sign convention: P > 0 is TENSION.

Surface so far: `model`, `clearance`, `cases` (Session 1); `kernel` (Session 2);
`mechanisms` (Session 3); `allowables` and `sweep` (Session 5); `serialize`
(Session 6); `failsafe` (Session 7); `optimize` — the layout search (Session 8).

`mechanisms.check()` is exported as `mechanism_check` to keep the bare name
`check` out of the package namespace.
"""

